window.changeLanguage = function(lang) {
    localStorage.setItem('app_lang', lang);
    applyLanguage(lang);
};

window.applyLanguage = function(lang) {
    const dict = translations[lang] || translations['de'];
    
    // Finde alle Elemente mit data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                el.innerText = dict[key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key]) {
            el.title = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (dict[key]) {
            el.setAttribute('aria-label', dict[key]);
        }
    });

    // Eventuell Sprachauswahl-Selects synchronisieren
    const select = document.getElementById('settingsLanguage');
    if (select) select.value = lang;
    
    document.documentElement.lang = lang;
};

window.t = function(key, fallback = '') {
    const lang = localStorage.getItem('app_lang') || 'de';
    return (translations[lang] && translations[lang][key]) || fallback || key;
};

// Initialisierung bei Script-Load
document.addEventListener('DOMContentLoaded', () => {
    const lang = localStorage.getItem('app_lang') || 'de';
    window.applyLanguage(lang);
});
